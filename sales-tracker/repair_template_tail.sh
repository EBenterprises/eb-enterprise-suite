#!/bin/bash
set -euo pipefail

for v in v1 v2 v3 v4 v5; do
    file="instances/$v/server.js"

    echo "=== Repairing $file ==="

    cp "$file" "$file.bak.$(date +%Y%m%d-%H%M%S)"

    python3 - "$file" <<'PY'
from pathlib import Path
import sys

path = Path(sys.argv[1])
s = path.read_text()

# The HTML response begins with:
#     res.send(`<!DOCTYPE html>
# and therefore must close with `); BEFORE app.listen().
#
# Replace the corrupted tail beginning at the existing loadData call.
marker = "loadData().then(() => {"
idx = s.rfind(marker)

if idx == -1:
    raise SystemExit(f"ERROR: tail marker not found in {path}")

prefix = s[:idx].rstrip()

# Everything after the marker was generated by the previous repair attempts.
# Rebuild the client tail, close the HTML template literal, close the route,
# then start the actual Express listener as JavaScript.
tail = r'''
loadData().then(() => {
    if (typeof tab !== 'undefined') {
        if (tab === "cust" && typeof renderProfilesList === "function") {
            renderProfilesList(allCustomersData);
        } else if (tab === "bals" && typeof renderBalancesList === "function") {
            renderBalancesList(allCustomersData);
        } else if (tab === "hist" && typeof renderGlobalHistory === "function") {
            renderGlobalHistory();
        } else if (tab === "sets" && typeof renderPresetConfig === "function") {
            renderPresetConfig();
        }
    }
}).catch(err => {
    console.error("Failed to load data for tab:", err);
});
</script>
</body>
</html>
`);
});

app.listen(PORT, "0.0.0.0", () => {
    console.log("Server running on port " + PORT);
});
'''

path.write_text(prefix + "\n" + tail)
PY

    if node --check "$file"; then
        echo "[PASS] $file syntax OK"
    else
        echo "[FAIL] $file syntax error"
        exit 1
    fi
done

echo
echo "[+] All five server.js files pass Node syntax validation."
