const fs = require('fs');
const path = require('path');

// 1. Let's inspect server.js and fix both the generic /api endpoint and any frontend handlers for update_tx
const serverPath = path.join(__dirname, 'server.js');
if (fs.existsSync(serverPath)) {
    let serverCode = fs.readFileSync(serverPath, 'utf8');

    // Make sure the general POST /api handler processes action === 'update_tx' correctly for all versions (v1-v5)
    // Let's replace or inject a bulletproof update_tx handler right at the top of the api handler
    const apiUpdateHandler = `
    if (action === 'update_tx') {
        const txsFile = DATA_FILE || path.join(__dirname, 'data.json');
        let txsData = [];
        try {
            if (fs.existsSync(txsFile)) {
                let raw = JSON.parse(fs.readFileSync(txsFile, 'utf8'));
                txsData = Array.isArray(raw) ? raw : (raw.transactions || raw.txs || []);
            }
        } catch (e) {}

        const targetId = Number(payload.id);
        const t = txsData.find(x => Number(x.id) === targetId);
        if (t) {
            t.customer = payload.customer !== undefined ? payload.customer : t.customer;
            t.landmark = payload.landmark !== undefined ? payload.landmark : t.landmark;
            t.amount = payload.amount !== undefined ? Number(payload.amount) : t.amount;
            t.cashCollected = payload.cashCollected !== undefined ? Number(payload.cashCollected) : t.cashCollected;
            
            if (payload.customTimestamp) {
                const customTs = new Date(payload.customTimestamp).getTime();
                if (!isNaN(customTs)) {
                    t.timestamp = customTs;
                    t.id = customTs;
                    t.date = payload.customTimestamp.replace('T', ' ');
                }
            }

            fs.writeFileSync(txsFile, JSON.stringify(txsData, null, 2));
            return res.writeHead(200, { 'Content-Type': 'application/json' }).end(JSON.stringify({ success: true, tx: t }));
        }
        return res.writeHead(404, { 'Content-Type': 'application/json' }).end(JSON.stringify({ success: false, error: 'Transaction not found' }));
    }
    `;

    // Inject this update_tx check right after action is parsed in the api handler
    if (serverCode.includes("let action =") || serverCode.includes("const action =")) {
        serverCode = serverCode.replace(
            /(let|const)\s+action\s*=\s*[^;]+;/i,
            match => match + '\n' + apiUpdateHandler
        );
    }

    // Also patch the frontend updateTx function inside the HTML strings generated by createAppHandler
    // to ensure it sends the correct payload format and reloads data properly.
    const newFrontendUpdateTx = `
function updateTx(id) {
    const custEl = document.getElementById('edit_cust_' + id);
    const landEl = document.getElementById('edit_land_' + id);
    const amtEl = document.getElementById('edit_amt_' + id);
    const cashEl = document.getElementById('edit_cash_' + id);
    const tsEl = document.getElementById('edit_ts_' + id);

    const payload = {
        id: Number(id),
        customer: custEl ? custEl.value : '',
        landmark: landEl ? landEl.value : '',
        amount: amtEl ? parseFloat(amtEl.value) || 0 : 0,
        cashCollected: cashEl ? parseFloat(cashEl.value) || 0 : 0,
        customTimestamp: tsEl ? tsEl.value : null
    };

    fetch('/api', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ action: 'update_tx', payload })
    })
    .then(res => res.json())
    .then(data => {
        if (data.success) {
            alert('Changes saved successfully!');
            if (typeof loadData === 'function') {
                loadData();
            } else {
                location.reload();
            }
        } else {
            alert('Error: ' + (data.error || 'Failed to save changes'));
        }
    })
    .catch(err => {
        console.error(err);
        alert('Network error while saving changes.');
    });
}
`;

    // Replace old updateTx in server.js templates
    if (serverCode.includes('function updateTx')) {
        serverCode = serverCode.replace(/function updateTx\([\s\S]*?\n\}/g, newFrontendUpdateTx);
    } else {
        serverCode = serverCode.replace('</script>', newFrontendUpdateTx + '\n</script>');
    }

    fs.writeFileSync(serverPath, serverCode);
    console.log("[+] Successfully patched server.js with robust universal backend & frontend save handlers!");
}
